#WINDOW FUNCTIONS: ALSO KNOWN AS ANALYTIC FUNCTIONS
#IT DEFINES BY AN OVER() CLAUSE
#ALLOWS U TO PERFORM CALCULATIONS ACROSS A SET OF ROWS RELATED TO THE CURRENT ROW
USE SCHOOL_DB;

SELECT FNAME,SALARY,SUM(SALARY) OVER() AS TOTAL_SAL,CAST(SALARY * 100 / SUM(SALARY) OVER() AS DECIMAL(10,2)) AS PERCENTAGE FROM EMPLOYEES;
#HERE WE SEE GROUP BY VS PARTITION BY
#OVER(PARTITION BY COL)
#OVER(ORDER BY COL)
#OVER(PARTION BY COL1 ORDER BY COL2)
SELECT FNAME,DEPARTMENT,SALARY,SUM(SALARY) OVER(PARTITION BY DEPARTMENT) AS TOTAL_DEPT_SAL FROM EMPLOYEES;


#WINDOW FUNCTION: ADDING ROW NUMBER
#ROW_NUMBER()  #RANK()   #DENSE_RANK()     #LAG()    LEAD()
SELECT ROW_NUMBER() OVER(ORDER BY EMP_ID) AS S_NO,FNAME,DEPARTMENT,SALARY FROM EMPLOYEES;
SELECT FNAME,DEPARTMENT,SALARY,RANK() OVER (ORDER BY SALARY DESC) AS RANK_OF_EMPLOYEES_ACC_TO_SAL FROM EMPLOYEES;
SELECT FNAME,DEPARTMENT,SALARY,DENSE_RANK() OVER (ORDER BY SALARY DESC) AS RANK_OF_EMPLOYEES_ACC_TO_SAL FROM EMPLOYEES;


#RANK VS DENSE_RANK: 
#- RANK(): Assigns the same rank to tied values but skips the next rank.
#DENSE_RANK(): Assigns the same rank to tied values without skipping the next rank.

#LAG(): Returns the value from a previous row in the result set.
#LEAD(): Returns the value from a subsequent (next) row in the result set.
#ROW_NUMBER():Assigns a unique sequential number to every row, even when values are identical.

SELECT FNAME,SALARY,DEPARTMENT,LAG(SALARY) OVER(ORDER BY SALARY DESC) AS PREV_SAL FROM EMPLOYEES;
SELECT FNAME,SALARY,DEPARTMENT,LEAD (SALARY) OVER(ORDER BY SALARY DESC) AS PREV_SAL FROM EMPLOYEES;


#TASKS OF WINDOW FUNCTIONS
SELECT FNAME,DEPARTMENT,SALARY,RANK() OVER (PARTITION BY DEPARTMENT ORDER BY SALARY DESC) AS DEPT_RANK FROM EMPLOYEES;
SELECT FNAME,DEPARTMENT,SALARY,DENSE_RANK() OVER (PARTITION BY DEPARTMENT ORDER BY SALARY DESC) AS DEPT_RANK FROM EMPLOYEES;

#MOST COMMON USE CASE OF WINDOW FUNCTION: RUNNING TOTAL CALCULATION 
SELECT FNAME,DEPARTMENT,SALARY,SUM(SALARY) OVER (PARTITION BY DEPARTMENT ORDER BY EMP_ID ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS RUNNING_TOTAL FROM EMPLOYEES;
SELECT FNAME,DEPARTMENT,SALARY,SUM(SALARY) OVER (PARTITION BY DEPARTMENT ORDER BY EMP_ID) AS RUNNING_TOTAL FROM EMPLOYEES;

SELECT FNAME,HIRE_DATE,SALARY,DEPARTMENT,LAG(SALARY) OVER(ORDER BY HIRE_DATE,EMP_ID) AS PREV_HIRE_SAL FROM EMPLOYEES;




#ROWS BETWEEN
SELECT FNAME,DEPARTMENT,SALARY,SUM(SALARY) OVER (PARTITION BY DEPARTMENT ORDER BY EMP_ID ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS RUNNING_TOTAL FROM EMPLOYEES;
SELECT FNAME,DEPARTMENT,SALARY,SUM(SALARY) OVER (PARTITION BY DEPARTMENT ORDER BY EMP_ID RANGE BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS RUNNING_TOTAL FROM EMPLOYEES;


SELECT FNAME, SALARY,FIRST_VALUE(SALARY) OVER (ORDER BY SALARY DESC) AS FIRST_SALARY FROM EMPLOYEES;
SELECT FNAME,SALARY,LAST_VALUE(SALARY) OVER (ORDER BY SALARY DESC) AS LAST_SALARY FROM EMPLOYEES;
SELECT FNAME,SALARY,LAST_VALUE(SALARY) OVER (ORDER BY SALARY DESC ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS LAST_SALARY FROM EMPLOYEES;
SELECT FNAME, DEPARTMENT,SALARY,NTILE(2) OVER (ORDER BY SALARY DESC) AS BUCKET_NO FROM EMPLOYEES;


