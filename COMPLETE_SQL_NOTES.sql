#INDEXES: POWERFUL WAY TO IMPROVE DATABASE PERFORMANCE
#Index is a database object used to speed up data retrieval from a table. It works like an index in a book.

#Advantages:#Faster SELECT queries. #Faster WHERE filtering.   #Faster JOIN operations.  #Helps with ORDER BY and GROUP BY.
#Disadvantages:#Requires extra storage.   #INSERT, UPDATE and DELETE can become slower.  #Too many indexes affect performance.


#TRIGGERS:Trigger is a database object that automatically executes a set of SQL statements when a specific event occurs on a table.



#TYPES OF TRIGGERS
#BEFORE INSERT	-> Before inserting a row
#AFTER INSERT ->	After inserting a row
#BEFORE UPDATE	-> Before updating a row
#AFTER UPDATE	-> After updating a row
#BEFORE DELETE	-> Before deleting a row
#AFTER DELETE	-> After deleting a row

#MySQL supports these 6 types of triggers.

#Advantages:  Automatic execution.  Maintains data consistency.    Useful for audit logs.  Helps enforce business rules.
#Disadvantages: Can make debugging difficult.  May affect performance.  Hidden execution can make code harder to understand.  Trigger errors can cause the original operation to fail.